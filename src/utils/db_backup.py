"""
src/utils/db_backup.py
======================
Respaldo semanal de la base en la PC del dueño (11-nov-26).

El 9-nov Neon bloqueó la base por pasarse del plan gratis: no se podía ni
leer, y no había ninguna copia. Mudarse a otro servicio era imposible y todo
lo que el programa junta (picks, apuestas sombra, momios guardados, Kalshi,
lo aprendido) quedó atrapado hasta que se pagó un plan.

El dashboard (que corre en la PC del dueño todos los días) hace la copia sola:
- cada 7 días, todas las tablas menos lo que se vuelve a descargar
  (historical_odds de football-data) y las tablas *_backup;
- cada 28 días, además el historial de partidos (matches y compañía).
Cada tabla va con COPY ... TO STDOUT en CSV comprimido, más schema.json para
rehacer tablas, restricciones, índices y secuencias, y manifest.json con las
filas. Se escribe en una carpeta .tmp que solo se renombra al terminar: una
copia a medias nunca parece completa. Ninguna copia se borra.

Gasto: ~40 MB de transferencia por copia semanal y ~25 MB más la mensual,
alrededor del 4% del plan gratis al mes. Queda en pipeline_runs como
"respaldo" (bytes_read) para el presupuesto (db_budget) y para el chequeo de
salidas, que avisa si la última copia tiene más de 10 días.

Restaurar: scripts/restore_backup.py (ensayo por defecto).
"""

import gzip
import json
import re
import sys
import time
from datetime import date, datetime, timezone
from pathlib import Path

BACKUP_EVERY_D = 7
FULL_EVERY_D = 28
LATE_D = 10
EXCLUDE = {"historical_odds"}                       # se vuelve a bajar de football-data
MONTHLY = {"matches", "match_events", "matches_history", "espn_matches"}
_SEQ = re.compile(r"nextval\('(?:public\.)?([^']+)'::regclass\)")


def is_backup_table(t: str) -> bool:
    return "_backup" in t or t.startswith("backup_")


def plan_tables(all_tables, full: bool) -> list:
    return sorted(t for t in all_tables
                  if t not in EXCLUDE and not is_backup_table(t) and (full or t not in MONTHLY))


def backup_root() -> Path:
    """installer/dist/respaldos junto al exe; en el repo, respaldos/."""
    base = Path(sys.executable).parent if getattr(sys, "frozen", False) else Path(__file__).resolve().parents[2]
    return base / "respaldos"


def existing(root: Path) -> list:
    """[(fecha, completa)] de las copias terminadas (las que tienen manifest)."""
    out = []
    for d in (root.iterdir() if root.exists() else []):
        m = d / "manifest.json"
        if d.is_dir() and not d.name.endswith(".tmp") and m.exists():
            try:
                man = json.loads(m.read_text(encoding="utf-8"))
                out.append((date.fromisoformat(man["date"]), bool(man.get("full"))))
            except Exception:
                continue
    return sorted(out)


def due(copies: list, today: date) -> tuple:
    """(toca copia, completa)."""
    last = max((d for d, _ in copies), default=None)
    last_full = max((d for d, f in copies if f), default=None)
    full = last_full is None or (today - last_full).days >= FULL_EVERY_D
    return (last is None or (today - last).days >= BACKUP_EVERY_D or full), full


# ── El esquema ───────────────────────────────────────────────────────────────

def table_schema(conn, table: str) -> dict:
    """Lo necesario para rehacer la tabla en una base vacía."""
    from sqlalchemy import text
    reg = f'public."{table}"'
    cols = conn.execute(text("""
        SELECT a.attname, format_type(a.atttypid, a.atttypmod), a.attnotnull,
               pg_get_expr(d.adbin, d.adrelid), a.attidentity
        FROM pg_attribute a LEFT JOIN pg_attrdef d ON d.adrelid = a.attrelid AND d.adnum = a.attnum
        WHERE a.attrelid = to_regclass(:t) AND a.attnum > 0 AND NOT a.attisdropped ORDER BY a.attnum
    """), {"t": reg}).fetchall()
    defs, seqs = [], []
    for name, typ, notnull, default, identity in cols:
        col = f'"{name}" {typ}'
        if identity in ("a", "d"):
            col += " GENERATED BY DEFAULT AS IDENTITY"
            seqs.append({"column": name, "identity": True})
        elif default:
            m = _SEQ.search(default)
            if m:
                seqs.append({"column": name, "sequence": m.group(1)})
                default = _SEQ.sub(f"nextval('{m.group(1)}'::regclass)", default)
            col += f" DEFAULT {default}"
        if notnull:
            col += " NOT NULL"
        defs.append(col)
    cons = conn.execute(text("""
        SELECT conname, contype, pg_get_constraintdef(oid) FROM pg_constraint
        WHERE conrelid = to_regclass(:t) AND contype IN ('p', 'u', 'c', 'x', 'f') ORDER BY contype, conname
    """), {"t": reg}).fetchall()
    idx = conn.execute(text("""
        SELECT indexname, indexdef FROM pg_indexes WHERE schemaname = 'public' AND tablename = :n
          AND indexname NOT IN (SELECT conname FROM pg_constraint WHERE conrelid = to_regclass(:t))
        ORDER BY indexname
    """), {"t": reg, "n": table}).fetchall()
    return {
        "create": f'CREATE TABLE "{table}" (\n  ' + ",\n  ".join(defs) + "\n)",
        "constraints": [{"name": n, "type": c, "sql": f'ALTER TABLE "{table}" ADD CONSTRAINT "{n}" {d}'}
                        for n, c, d in cons],
        "indexes": [d.replace(" ON public.", " ON ") for _, d in idx],
        "sequences": seqs,
    }


# ── La copia ─────────────────────────────────────────────────────────────────

class _Counter:
    """Archivo que cuenta lo que pasa por él (los bytes que vinieron de la base)."""

    def __init__(self, f):
        self.f, self.n = f, 0

    def write(self, b):
        self.n += len(b)
        return self.f.write(b)


def run_backup(engine, root: Path | None = None, today: date | None = None, full: bool | None = None,
               log=print) -> dict:
    from sqlalchemy import text
    root = root or backup_root()
    today = today or datetime.now(timezone.utc).date()
    if full is None:
        full = due(existing(root), today)[1]
    started = time.time()
    with engine.connect() as conn:
        tables = [r[0] for r in conn.execute(text("SELECT tablename FROM pg_tables WHERE schemaname = 'public'"))]
        plan = plan_tables(tables, full)
        schema = {t: table_schema(conn, t) for t in plan}
    name = today.isoformat()
    n = 2
    while (root / name).exists():
        name = f"{today.isoformat()}-{n}"
        n += 1
    tmp = root / (name + ".tmp")
    tmp.mkdir(parents=True, exist_ok=True)
    (tmp / "schema.json").write_text(json.dumps(schema, indent=1, ensure_ascii=False), encoding="utf-8")
    manifest = {"date": today.isoformat(), "full": full, "tables": {}, "started": datetime.now(timezone.utc).isoformat()}
    raw = engine.raw_connection()
    try:
        cur = raw.cursor()
        for t in plan:
            with gzip.open(tmp / f"{t}.csv.gz", "wb", compresslevel=6) as gz:
                counter = _Counter(gz)
                cur.copy_expert(f'COPY (SELECT * FROM public."{t}") TO STDOUT WITH (FORMAT csv, HEADER true)', counter)
            manifest["tables"][t] = {"rows": int(cur.rowcount if cur.rowcount is not None else -1), "bytes": counter.n}
        raw.rollback()
    finally:
        raw.close()
    manifest["bytes"] = sum(v["bytes"] for v in manifest["tables"].values())
    manifest["seconds"] = round(time.time() - started, 1)
    (tmp / "manifest.json").write_text(json.dumps(manifest, indent=1), encoding="utf-8")
    final = root / name
    tmp.rename(final)
    log(f"💾 Respaldo {'completo' if full else 'semanal'} en {final}: {len(plan)} tablas, "
        f"{sum(v['rows'] for v in manifest['tables'].values()):,} filas, {manifest['bytes'] / 1e6:.1f} MB")
    try:
        from src.utils.pipeline_runs import record_run
        record_run(engine, "respaldo", 0, manifest["seconds"], sum(v["rows"] for v in manifest["tables"].values()),
                   None, manifest["bytes"], None)
    except Exception as e:
        log(f"⚠️  Respaldo: no se pudo anotar en pipeline_runs ({type(e).__name__})")
    return manifest


def maybe_backup(engine, root: Path | None = None, log=print) -> dict | None:
    root = root or backup_root()
    go, full = due(existing(root), datetime.now(timezone.utc).date())
    if not go:
        return None
    return run_backup(engine, root, full=full, log=log)


def backup_late(last_run, now: datetime | None = None) -> str | None:
    """Chequeo de salidas: la última copia (pipeline_runs "respaldo")."""
    import pandas as pd
    now = pd.Timestamp(now or datetime.now(timezone.utc))
    if last_run is None or pd.isna(last_run):
        return ("Respaldo de la base: todavía no hay ninguna copia en la PC (la hace el dashboard "
                "cada semana; ¿está abierto con la versión 2.12.0 o más nueva?)")
    last = pd.Timestamp(last_run)
    last = last.tz_localize("UTC") if last.tzinfo is None else last
    days = (now - last).total_seconds() / 86400
    if days > LATE_D:
        return (f"Respaldo de la base: la última copia en la PC es de hace {days:.0f} días (toca cada "
                f"{BACKUP_EVERY_D}); el dashboard no ha estado abierto o la copia falla")
    return None


# ── Restaurar ────────────────────────────────────────────────────────────────

def restore(engine, folder: Path, schema: str | None = None, apply: bool = False, log=print) -> dict:
    """Rehace las tablas de la copia en `schema` (o en public de una base
    vacía) y compara las filas con el manifest. Sin apply, todo va en una
    transacción que se deshace al final: sirve de ensayo sin dejar nada."""
    folder = Path(folder)
    man = json.loads((folder / "manifest.json").read_text(encoding="utf-8"))
    sch = json.loads((folder / "schema.json").read_text(encoding="utf-8"))
    raw = engine.raw_connection()
    counts = {}
    try:
        cur = raw.cursor()
        if schema:
            if not re.fullmatch(r"[a-z_][a-z0-9_]*", schema):
                raise ValueError("schema: solo minúsculas, números y _")
            cur.execute(f'CREATE SCHEMA "{schema}"')
            cur.execute(f'SET LOCAL search_path TO "{schema}"')
        for t, s in sch.items():
            for q in s["sequences"]:
                if q.get("sequence"):
                    cur.execute(f'CREATE SEQUENCE IF NOT EXISTS "{q["sequence"]}"')
            cur.execute(s["create"])
        for t in sch:
            with gzip.open(folder / f"{t}.csv.gz", "rb") as gz:
                cur.copy_expert(f'COPY "{t}" FROM STDIN WITH (FORMAT csv, HEADER true)', gz)
            cur.execute(f'SELECT COUNT(*) FROM "{t}"')
            counts[t] = cur.fetchone()[0]
        for t, s in sch.items():
            for c in sorted(s["constraints"], key=lambda c: c["type"] == "f"):   # las foráneas al final
                cur.execute(c["sql"])
            for i in s["indexes"]:
                cur.execute(i)
            for q in s["sequences"]:                     # que el próximo id siga después del último
                seq = (f"'\"{q['sequence']}\"'" if q.get("sequence")
                       else f"pg_get_serial_sequence('\"{t}\"', '{q['column']}')")
                cur.execute(f'SELECT setval({seq}, COALESCE(MAX("{q["column"]}"), 0) + 1, false) FROM "{t}"')
        bad = {t: (counts[t], man["tables"][t]["rows"]) for t in counts
               if man["tables"].get(t, {}).get("rows", -1) >= 0 and counts[t] != man["tables"][t]["rows"]}
        if bad:
            raise RuntimeError(f"filas distintas a las de la copia: {bad}")
        (raw.commit if apply else raw.rollback)()
        log(f"{'✅ Restaurado' if apply else '↩ Ensayo de restauración correcto (nada se guardó)'}: "
            f"{len(counts)} tablas, {sum(counts.values()):,} filas" + (f" en el esquema {schema}" if schema else ""))
    except Exception:
        raw.rollback()
        raise
    finally:
        raw.close()
    return counts


def start_thread(engine, first_delay_s: float = 120, every_s: float = 6 * 3600) -> None:
    """Hilo del dashboard: a los 2 min de abrir y luego cada 6 h revisa si toca."""
    import threading
    root = backup_root()

    def log(msg):
        try:
            root.mkdir(parents=True, exist_ok=True)
            with open(root / "respaldo.log", "a", encoding="utf-8") as f:
                f.write(f"{datetime.now():%Y-%m-%d %H:%M} {msg}\n")
        except Exception:
            pass

    def loop():
        time.sleep(first_delay_s)
        while True:
            try:
                maybe_backup(engine, root, log=log)
            except Exception as e:
                log(f"❌ Respaldo falló: {type(e).__name__}: {str(e)[:200]}")
            time.sleep(every_s)
    threading.Thread(target=loop, name="respaldo", daemon=True).start()
